// Static contract checks for account-gated TAKATAK SEO free tools.
// Run with: npm run qa:seo-free-tools
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { SEO_CATEGORIES, SEO_FREE_TOOLS } from "../src/lib/seo/free-tools-catalog";

const source = (path:string)=>readFileSync(path,"utf8");
assert.equal(SEO_CATEGORIES.length,4,"All required groups should be present.");
assert.equal(SEO_FREE_TOOLS.length,23,"All 23 requested free tools should be represented.");
assert.equal(new Set(SEO_FREE_TOOLS.map(t=>t.id)).size,23,"Tool ids are unique.");
for(const tool of SEO_FREE_TOOLS){
 assert.ok(tool.title.length>4&&tool.description.length>15,tool.id+" has clear copy");
 assert.ok(SEO_CATEGORIES.includes(tool.category),tool.id+" is in a valid category");
 assert.ok(["live","generator","text","provider"].includes(tool.mode),tool.id+" has an honest execution mode");
}
assert.equal(SEO_FREE_TOOLS.filter(t=>t.mode==="live").length,9);
assert.equal(SEO_FREE_TOOLS.filter(t=>t.mode==="generator").length,4);
assert.equal(SEO_FREE_TOOLS.filter(t=>t.mode==="text").length,2);
assert.equal(SEO_FREE_TOOLS.filter(t=>t.mode==="provider").length,8);

const privatePage=source("src/app/dashboard/seo/free-tools/page.tsx");
const publicPage=source("src/app/(website)/free-tools/page.tsx");
const action=source("src/app/dashboard/seo/free-tools/actions.ts");
const portfolio=source("src/lib/seo/seotakatak-bridge.ts");
assert.match(privatePage,/requireGrowthAccess\(/,"Dashboard route uses existing TAKATAK Auth");
assert.match(privatePage,/access.mode!=="client_scoped"/,"Dashboard requires a selected tenant");
assert.match(publicPage,/href="\/register"/,"Public directory links to TAKATAK registration");
assert.match(action,/access.mode!=="client_scoped"/,"Server action rechecks tenant");
assert.match(action,/fetchPublicPage\(/,"Live scanning reuses pinned-address fetch");
assert.match(action,/listGoogleLinkedSites\(access.activeClientId\)/,"Google inspection uses scoped verified properties");
assert.match(portfolio,/tenant_id:input.tenantId/,"SEO API token derives tenant from trusted access");
assert.match(portfolio,/manage_integrations/,"Portfolio writes require authorization");
const portfolioActions=source("src/app/dashboard/seo/portfolio/actions.ts");
const portfolioPage=source("src/app/dashboard/seo/portfolio/page.tsx");
const evidencePage=source("src/app/dashboard/seo/portfolio/[siteId]/page.tsx");
const csvRoute=source("src/app/api/seo/sites/[siteId]/opportunities.csv/route.ts");
assert.match(portfolio,/permissions:input.ingest\?\["seo:import"\]/,"Ingest-only scope is separate from a manager token");
assert.match(portfolio,/getSeoEvidenceSummary/,"Evidence is requested from server-side backend");
assert.match(portfolio,/downloadSeoOpportunities/,"CSV download stays server side");
assert.match(portfolioActions,/listGoogleLinkedSites\(access.activeClientId\)/,"Google queries scoped to active client");
assert.match(portfolioActions,/fetchSearchQueries\(/,"Importer reads actual Google Search Console");
assert.match(portfolioActions,/hostname\(s.domain\)===hostname\(site.domain\)/,"Imported property must match managed site domain");
assert.match(portfolioPage,/importSeoSearchConsoleQueries/,"Portfolio exposes real import action");
assert.match(evidencePage,/view_reports/,"Evidence requires report permission");
assert.match(csvRoute,/downloadSeoOpportunities/,"CSV route uses signed secure server adapter");
assert.match(csvRoute,/Cache-Control.*private, no-store/,"CSV is never publicly cached");
const backlinkActions=source("src/app/dashboard/seo/portfolio/[siteId]/actions.ts");
const backlinkPage=source("src/app/dashboard/seo/portfolio/[siteId]/page.tsx");
assert.match(portfolio,/getSeoProspects/,"Backlink prospects are sourced from scoped SEO backend");
assert.match(portfolio,/updateSeoProspectStatus/,"Backlink status changes pass through signed server bridge");
assert.match(backlinkActions,/addSeoProspect/,"Editorial prospects have a real create action");
assert.match(backlinkPage,/changeBacklinkProspectStatus/,"Editorial status updates are live");
assert.doesNotMatch(backlinkPage,/<option value="earned">/,"Unverified backlinks must not be marked earned");
const domainActions=source("src/app/dashboard/seo/portfolio/[siteId]/actions.ts");
assert.match(portfolio,/getSeoDomainVerification/,"DNS challenges are requested via TAKATAK signed backend");
assert.match(portfolio,/manageSeoDomainVerification/,"Domain verification action uses the server-only bridge");
assert.match(backlinkPage,/Verify domain ownership \(DNS TXT\)/,"Client dashboard offers real DNS verification instructions");
assert.match(domainActions,/changeSeoDomainVerification/,"DNS verification uses authenticated server action");
const contentActions=source("src/app/dashboard/seo/portfolio/[siteId]/actions.ts");
assert.match(portfolio,/getSeoContentBriefs/,"Draft briefs are read from the tenant-scoped backend");
assert.match(portfolio,/addSeoContentBrief/,"Draft briefs are saved through signed TAKATAK service");
assert.match(contentActions,/createSeoContentBrief/,"Client can submit a brief through a real server action");
assert.match(backlinkPage,/Draft only — not published/,"Content brief UI does not claim automated publishing");
assert.match(portfolio,/removeSeoManagedSite/,"Domain-confirmed deletion uses only the signed tenant-scoped SEO backend");
assert.match(portfolioActions,/deleteSeoManagedSite/,"SEO site deletion is a real server action");
assert.match(portfolioPage,/approveDeletion/,"Destructive action requires separate affirmative confirmation");
assert.match(portfolioPage,/confirmDomain/,"Destructive action requires the exact site domain");
assert.match(portfolio,/decideSeoContentBrief/,"Human review decision goes through signed backend");
assert.match(contentActions,/reviewSeoContentBrief/,"Human review submission has a real server action");
assert.match(backlinkPage,/Approved for editorial planning — not published/,"Approval never misrepresents CMS publication");
const seoJsonExport=source("src/app/api/seo/sites/[siteId]/snapshot.json/route.ts");
assert.match(portfolio,/downloadSeoSiteSnapshot/,"SEO snapshot is requested from server-only signed bridge");
assert.match(portfolio,/view_reports/,"Data export requires active report access");
assert.match(evidencePage,/snapshot\.json/,"Client report offers honest, capped SEO JSON export");
assert.match(seoJsonExport,/Cache-Control.*private, no-store/,"Client SEO export is never cached publicly");
assert.match(seoJsonExport,/downloadSeoSiteSnapshot/,"JSON export route verifies tenant-scoped backend access");
console.log("SEO free tools: 23 catalog entries and TAKATAK access contracts PASS");
